package dev.picasso.middleware

/**
 * 이 자리가 속한 **작업 구역**(§15.153).
 *
 * ## 반경이 아니라 구역이다
 *
 * 두 기체의 작업 반경이 겹치면 그것도 셀 전용 자원의 경쟁이다. 그런데 이 저장소에는 좌표도 반경도 없고
 * (그것은 어댑터 경계 밖의 지식이다) 미믹에 기하가 없어 **반경 겹침을 틀리게 만들 방법이 없다** —
 * 그렇게 지으면 항상 통과하는 시험이 된다.
 *
 * 그래서 공간을 **구역 이름**으로 다룬다. 맞대 볼 토큰이라 어긋나게 만들 수 있고, 그래서 시뮬레이션에서
 * 진짜로 검증된다. 자리 결속의 좌표 칸과 바닥 소유자를 같은 이유로 이름으로 다뤘다(§15.156 · §15.162).
 *
 * **대가는 성기다는 것이다.** 같은 구역의 두 기체가 실제로는 안 겹칠 수 있다. 세밀하게 가르려면 기하가
 * 필요하고 그것은 실물이 붙을 때의 일이다(§15.163).
 */
interface Workspace {

    /**
     * 이 자리가 속한 구역. **선언 안 됐으면 `null`** 이고 그때는 검사하지 않는다.
     *
     * 모르는 자리를 «어느 구역도 아니다» 로 단정하지 않는다 — 구역을 안 붙인 배치에서 라인이 통째로
     * 서면 이 관문이 곧 꺼진다.
     */
    fun zoneOf(location: String): String?

    /** 구역을 안 붙인 배치. 기본값이다. */
    object None : Workspace {
        override fun zoneOf(location: String): String? = null
    }
}

/**
 * 지금 그 구역에서 일하고 있는 쪽.
 *
 * **`destination` 의 두 뜻이 여기서는 둘 다 센다.** 놓을 자리든 갈 자리든 기체가 그 공간을 차지한다 —
 * 슬롯 점유가 «아는 것을 놓는 자리» 만 세는 것과 다른 점이고, 자원의 성질이 다르기 때문이다.
 */
data class ZoneUse(val zone: String, val executionId: String, val jobOrderId: String, val robotId: String)
