-- ADR 37 — **등록이 두 갈래다: 발견과 선언.**
--
-- 설계 §8.5의 조작 목록에 *기체 등록* 이 처음부터 있었는데 **엔드포인트가 없었다.**
-- 그래서 지금까지 기체 행은 시험이 `INSERT INTO robot` 으로 직접 넣었고, 미믹의
-- 기체 목록은 기동 인자로 손으로 적었다 — ADR 37 이 *"우리 하네스가 스스로 결정 5의
-- 비싼 사분면에 앉아 있다"* 고 적어 둔 그 상태다.
--
-- ## 출처는 **문이** 정한다
--
-- 결정 3 — 로봇 목록을 누가 만들었는가는 타입 필드로 적지 않고 **어느 문으로
-- 들어왔는가**가 그 사실이다.
--
--   발견 — 어댑터가 플릿에 물어 올린다 → 적재 문(`IngestToken`)   = "기체가 자기 관측을 보고한다"
--   선언 — 사람이 화면에서 적는다     → 조작 문(`OperatorToken`) = "사람이 판단을 기록한다"
--
-- 그래서 이 열은 **본문에서 오지 않는다.** 컨트롤러가 자기 경로를 보고 정하며,
-- 요청이 `origin` 을 실어 보내도 아무 일도 일어나지 않는다. 본문이 정하게 두면
-- 적재 토큰을 든 현장의 기체가 스스로 *"사람이 선언했다"* 고 적을 수 있고, 그
-- 승격은 `OperatorToken` 이 막으려던 바로 그것이다.
--
-- ## `NULL` 은 넷째 상태다 — **문 밖에서 들어온 행**
--
-- 기본값을 안 준다. 주면 SQL 로 직접 넣은 행이 *"사람이 선언했다"* 고 거짓말하고,
-- 그 거짓말은 진단 화면에서 진짜 선언과 구별되지 않는다. 비어 있는 것이 사실이며
-- 진단 9번이 그것을 `UNREGISTERED` 로 보여 준다. 시험 픽스처 스물다섯 자리가 지금
-- 그 상태이고, **보이는 편이 defaults 로 덮는 것보다 낫다.**
ALTER TABLE robot
    ADD COLUMN origin        TEXT,

    -- **직결에서만 우리가 갖는다**(결정 4). 플릿 경유면 접속 정보는 플릿이 갖고
    -- 우리는 안 갖는다 — 가지면 같은 사실이 두 곳에 있게 되고, 플릿에서 바뀐 것을
    -- 우리가 모른다.
    --
    -- **주소만이다. 자격증명은 여기 안 둔다** — §6.3이 신원·접근을 범위 밖에 뒀고,
    -- ADR 37이 대가로 *"접속 설정에 비밀이 섞인다"* 를 적어 뒀다. 비밀을 어디 둘지
    -- 정하기 전까지 이 열에 그것을 넣지 않는다. 넣는 순간 이 표가 자격증명 저장소가
    -- 되고, 그것은 이 프로젝트가 결정한 적 없는 일이다.
    ADD COLUMN endpoint      TEXT,

    ADD COLUMN registered_at TIMESTAMPTZ,

    -- 누가 등록했는가. 조작 문은 `X-Actor`(자기 신고, §15.3)이고 적재 문은 어댑터다.
    -- 부인방지가 아니라 조사 단서다.
    ADD COLUMN registered_by TEXT;

ALTER TABLE robot
    ADD CONSTRAINT robot_origin_known
        CHECK (origin IS NULL OR origin IN ('DECLARED', 'DISCOVERED'));

-- 결정 4를 **스키마가 든다.** 서비스가 거절하는 것과 별개로 여기서도 막는 이유는,
-- 발견된 기체의 접속 정보를 우리가 갖는 순간 그것이 플릿의 것과 두 번째 진실이 되기
-- 때문이다. 서비스를 한 줄 고쳐 새는 것을 표가 막는다.
ALTER TABLE robot
    ADD CONSTRAINT robot_discovered_has_no_endpoint
        CHECK (origin IS DISTINCT FROM 'DISCOVERED' OR endpoint IS NULL);
