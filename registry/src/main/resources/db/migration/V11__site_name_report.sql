-- 기체가 **자기가 아는 사이트 이름**을 보고한 것(ADR 35).
--
-- §15.68이 닫히면서 남긴 하나가 이것이었다 — *"기록이 '했다' 는 사람의 말이지
-- 관측이 아니다."* `robot_binding.site_names_registered_at` 은 운영자의 자기
-- 신고였고, 오타 하나나 빠뜨린 이름 하나를 아무도 못 잡았다.
--
-- 계약에 `GetKnownSiteNames` 가 생겨 기체가 답할 수 있게 됐고, 그 답이 생존
-- 보고에 실려 온다. 그러면 상태가 **"사람이 말했다"** 에서 **"기체도 그렇게
-- 답했다"** 로 올라간다.
--
-- ## 이름을 저장하지 않는다
--
-- 계약은 목록을 주지만 여기는 **개수와 '호스팅 못 함' 만** 받는다. 사이트
-- 이름의 주인은 사이트이고 `registry` 는 *"등록됐는가"* 만 상태로 든다
-- (ADR 35의 결정 3). 이름을 저장하면 그 표가 두 번째 진실이 되고, 사이트에서
-- 이름을 바꾼 날 어느 쪽이 맞는지 정해져 있지 않다.
--
-- **그래서 잡는 것과 못 잡는 것이 갈린다.** 통째로 안 했거나 엉뚱한 기체에
-- 했으면 개수가 0이라 잡힌다. **이름 하나를 오타 냈으면 개수가 같아 못
-- 잡는다.** 그것을 잡으려면 무엇을 등록했어야 하는지의 목록이 필요하고,
-- 그 목록을 registry 가 드는 순간 위 결정이 깨진다.

ALTER TABLE robot_liveness
    -- 기체가 이름을 호스팅하지 못한다고 답했는가. **개수 0과 다르다** —
    -- 앞은 등록할 자리가 없는 기종(§2.3의 Unitree)이고 뒤는 자리는 있는데
    -- 비어 있는 것이다. 접으면 자리가 없는 기체에게 등록을 요구하게 된다.
    --
    -- `NULL` 은 셋째 상태다: **아직 안 물어봤다.**
    ADD COLUMN site_names_unsupported BOOLEAN,

    -- 기체가 안다고 답한 이름의 개수. `NULL` 이면 안 물어본 것이다.
    ADD COLUMN site_names_count INT,

    -- 그 답을 받은 시각. `last_reported_at` 과 따로 두는 것은, 생존 보고가
    -- 이 값 없이도 올 수 있기 때문이다(옛 어댑터·브로커 경로).
    ADD COLUMN site_names_reported_at TIMESTAMPTZ;
